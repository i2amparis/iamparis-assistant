// Grade two recorded runs of the persona conversations against the expectation on each turn in
// personas.json, and write a before/after table.
//
//   node docs/persona-study/compare.mjs [before=baseline] [after=after] [--set personas|heldout]
//
// A turn passes when the reply kind is one of `expect.kind` and its signature (kind, filters,
// years, title, facet selection, first tools and studies, URL, first four options and text,
// lower-cased) contains every `expect.has` string and, when given, at least one `expect.any`.
// Writes results/comparison.md and prints the totals.
import { readFileSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2);
const at = args.indexOf("--set");
const set = at >= 0 ? args.splice(at, 2)[1] : "personas";
const [beforeLabel = "baseline", afterLabel = "after"] = args;
const load = (name) => JSON.parse(readFileSync(new URL(name, import.meta.url), "utf8"));
const { personas } = load(`./${set}.json`);
const before = load(`./results/${beforeLabel}.json`);
const after = load(`./results/${afterLabel}.json`);

function signature(turn) {
  return JSON.stringify({
    kind: turn.kind,
    filters: turn.filters,
    years: turn.years,
    title: turn.title,
    selection: turn.selection,
    studies: turn.studies?.slice(0, 3),
    tools: turn.tools?.slice(0, 3),
    url: turn.url,
    options: turn.options?.slice(0, 4),
    text: turn.text,
  }).toLowerCase();
}
function passes(turn, expect) {
  if (!turn) return false;
  const kinds = [expect.kind].flat();
  const said = signature(turn);
  return (
    kinds.includes(turn.kind) &&
    expect.has.every((s) => said.includes(s)) &&
    (!expect.any || expect.any.some((s) => said.includes(s)))
  );
}
/** A short description of what the assistant did in a turn. */
function did(turn) {
  if (!turn) return "–";
  const f = turn.filters ?? {};
  if (turn.kind === "result")
    return `result: ${f.variable?.join("+")} · ${f.region?.join("+")} · ${f.workspace_code}`;
  if (turn.kind === "ask" || turn.kind === "review")
    return `${turn.kind}: ${(turn.options ?? []).slice(0, 3).join(" / ")}`;
  if (turn.kind === "studies") return `studies: ${(turn.selection ?? []).join(", ")}`;
  if (turn.kind === "apps") return `tools: ${(turn.tools ?? []).slice(0, 2).join(" / ")}`;
  return `${turn.kind}: ${turn.title ?? ""}`;
}
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");

const lines = [
  `# Persona conversations: ${beforeLabel} vs ${afterLabel}`,
  "",
  `Generated by \`compare.mjs\` from \`results/${beforeLabel}.json\` (${before.started}) and \`results/${afterLabel}.json\` (${after.started}). ✓ = the reply meets the turn's \`expect\` in ${set}.json.`,
  "",
];
let total = 0;
let passedBefore = 0;
let passedAfter = 0;
for (const persona of personas) {
  const b = before.personas.find((p) => p.id === persona.id);
  const a = after.personas.find((p) => p.id === persona.id);
  lines.push(`## ${persona.id}: ${persona.who}`, "");
  lines.push("| # | User | Wanted | Before | After |", "|---|---|---|---|---|");
  persona.turns.forEach((turn, i) => {
    const ok = [passes(b?.turns[i], turn.expect), passes(a?.turns[i], turn.expect)];
    total++;
    passedBefore += ok[0];
    passedAfter += ok[1];
    lines.push(
      `| ${i + 1} | ${cell(turn.text)} | ${cell(turn.want)} | ${ok[0] ? "✓" : "✗"} ${cell(did(b?.turns[i]))} | ${ok[1] ? "✓" : "✗"} ${cell(did(a?.turns[i]))} |`,
    );
  });
  lines.push("");
}
lines.splice(4, 0, `**${passedBefore}/${total} turns before, ${passedAfter}/${total} after.**`, "");
const report = set === "personas" ? "comparison" : `comparison-${set}`;
writeFileSync(new URL(`./results/${report}.md`, import.meta.url), `${lines.join("\n")}\n`);
console.log(
  `${passedBefore}/${total} before, ${passedAfter}/${total} after. Wrote results/${report}.md`,
);
