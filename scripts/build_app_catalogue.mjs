// Build data/apps.json: every tool in the IAMPARIS Application Library
// (https://iamparis.eu/application_library) with what the library shows for it.
//
// The library page lists the CMS collection `Application_list` and links each entry to
// /application_library/<id>. This script reads the same collection, so the assistant can name a
// tool's own library page instead of sending people to the library to search for it.
//
//   node scripts/build_app_catalogue.mjs
//
// Rerun when applications are added, edited or removed in the CMS dashboard.
import { writeFileSync } from "node:fs";

const CMS = process.env.IAM_CMS_URL || "https://cms.iamparis.eu";

const response = await fetch(`${CMS}/items/Application_list?limit=-1`, {
  signal: AbortSignal.timeout(30000),
});
if (!response.ok) throw new Error(`${CMS} answered ${response.status}`);
const rows = (await response.json()).data;

const clean = (value) =>
  String(value ?? "")
    .replace(/<[^>]*>/g, " ")
    .replace(/\s+/g, " ")
    .trim();
const items = (value) =>
  clean(value)
    .split(",")
    .map((item) => item.trim())
    .filter(Boolean);
// One spelling per value, the most used one ("Climate Impacts", also entered as "Climate impacts").
const spelled = new Map();
for (const row of rows)
  for (const field of ["Type", "Main_topic", "Target_audiences", "Scale"])
    for (const item of items(row[field])) {
      const counts = spelled.get(item.toLowerCase()) ?? new Map();
      spelled.set(item.toLowerCase(), counts.set(item, (counts.get(item) ?? 0) + 1));
    }
const spelling = (item) =>
  [...(spelled.get(item.toLowerCase()) ?? [[item, 1]])].sort((a, b) => b[1] - a[1])[0][0];
/** A comma-separated CMS field as a list. */
const list = (value) => [...new Set(items(value).map(spelling))];
const web = (value) => {
  try {
    const url = new URL(clean(value));
    return url.protocol === "https:" || url.protocol === "http:" ? url.href : undefined;
  } catch {
    return undefined;
  }
};

const apps = rows
  .filter((row) => row.id != null && clean(row.Title))
  .map((row) => ({
    id: row.id,
    title: clean(row.Title),
    description: clean(row.Description),
    // The library page's detail route, and the tool itself.
    path: `/application_library/${row.id}`,
    link: web(row.Application_link),
    type: list(row.Type),
    topic: list(row.Main_topic),
    audiences: list(row.Target_audiences),
    scales: list(row.Scale),
    geographies: list(row.Geographies),
    // "see: https://…" is a pointer, not a name.
    creator: /https?:\/\//.test(clean(row.Created_by)) ? undefined : clean(row.Created_by),
    year: clean(row.Year_established) || undefined,
    project: clean(row._project) || undefined,
    catalogued_by: clean(row.First_catalogued_by) || undefined,
  }))
  .sort((a, b) => a.title.localeCompare(b.title));

/** A facet's values, most used first, as the type chips and topic questions offer them. */
const used = (key) => {
  const counts = new Map();
  for (const app of apps)
    for (const value of app[key]) counts.set(value, (counts.get(value) ?? 0) + 1);
  return [...counts]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([value]) => value);
};
const catalogue = {
  _comment:
    "Generated by scripts/build_app_catalogue.mjs from the CMS collection behind the IAMPARIS Application Library. Do not edit by hand: change the application in the CMS dashboard and rebuild.",
  generated_on: new Date().toISOString().slice(0, 10),
  source: "https://iamparis.eu/application_library",
  facets: { type: used("type"), topic: used("topic") },
  apps,
};
writeFileSync(
  new URL("../data/apps.json", import.meta.url),
  `${JSON.stringify(catalogue, null, 2)}\n`,
);
console.log(
  `${apps.length} applications written to data/apps.json (${catalogue.facets.type.length} types, ${catalogue.facets.topic.length} topics, ${apps.filter((a) => !a.link).length} without a link)`,
);
