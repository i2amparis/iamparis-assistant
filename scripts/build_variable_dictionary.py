"""Build data/variables.json: plain-language descriptions and units for IAMPARIS variables.

Source: the IAMC common-definitions YAML in iam-data-chatbot/definitions/variable. Templated
names such as "Secondary Energy|Electricity|{Electricity Source}" are expanded with the tag files
(tag_*.yaml); the tag value's description fills the placeholder in the variable's description.
Only variables that exist in at least one catalogued IAMPARIS study are kept, so the file stays
small and every entry is reachable.

    python scripts/build_variable_dictionary.py ../iam-data-chatbot/definitions/variable
"""

import itertools
import json
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
API = "https://api.iamparis.eu/results/distinct"


def load_tags(folder: pathlib.Path) -> dict[str, list[tuple[str, str]]]:
    import yaml

    tags: dict[str, list[tuple[str, str]]] = {}
    for path in folder.rglob("tag_*.yaml"):
        for block in yaml.safe_load(path.read_text(encoding="utf-8")) or []:
            for tag, values in block.items():
                for item in values or []:
                    for value, attrs in item.items():
                        description = (attrs or {}).get("description") or value
                        tags.setdefault(tag, []).append((value, " ".join(str(description).split())))
    return tags


def load_variables(folder: pathlib.Path, tags) -> dict[str, dict]:
    import yaml

    variables: dict[str, dict] = {}
    for path in folder.rglob("*.yaml"):
        if path.name.startswith("tag_"):
            continue
        for block in yaml.safe_load(path.read_text(encoding="utf-8")) or []:
            for name, attrs in block.items():
                attrs = attrs or {}
                description = " ".join(str(attrs.get("description", "")).split())
                unit = attrs.get("unit")
                placeholders = re.findall(r"\{([^}]+)\}", name)
                if not placeholders:
                    variables[name] = {"description": description, "unit": unit}
                    continue
                if any(p not in tags for p in placeholders):
                    continue
                for combo in itertools.product(*(tags[p] for p in placeholders)):
                    expanded, text = name, description
                    for placeholder, (value, value_description) in zip(placeholders, combo):
                        expanded = expanded.replace("{" + placeholder + "}", value)
                        text = text.replace("{" + placeholder + "}", value_description)
                    variables.setdefault(expanded, {"description": text, "unit": unit})
    return variables


def iamparis_variables() -> set[str]:
    catalogue = json.loads((ROOT / "data" / "workspaces.json").read_text(encoding="utf-8"))
    found: set[str] = set()
    for workspace in catalogue["workspaces"]:
        body = json.dumps({"workspace_code": [workspace["code"]], "column": "variable"}).encode()
        request = urllib.request.Request(API, body, {"Content-Type": "application/json"})
        with urllib.request.urlopen(request, timeout=60) as response:
            found.update(v for v in json.load(response)["data"] if v)
    return found


def main() -> None:
    folder = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ROOT.parent / "iam-data-chatbot" / "definitions" / "variable")
    tags = load_tags(folder)
    definitions = load_variables(folder, tags)
    used = iamparis_variables()
    for entry in definitions.values():
        if entry["unit"] and "{" in str(entry["unit"]):
            entry["unit"] = None
    dictionary = {name: definitions[name] for name in sorted(used) if name in definitions}
    # Project-specific variables get the nearest defined ancestor's description plus the rest of
    # the name, marked as derived so they can be curated later.
    for name in sorted(used - definitions.keys()):
        parts = name.split("|")
        for cut in range(len(parts) - 1, 0, -1):
            parent = definitions.get("|".join(parts[:cut]))
            if parent and parent["description"]:
                dictionary[name] = {
                    "description": f"{parent['description']} — {' / '.join(parts[cut:])}",
                    "unit": None,
                    "derived": True,
                }
                break
    out = ROOT / "data" / "variables.json"
    out.write_text(
        json.dumps(
            {
                "_comment": "Generated by scripts/build_variable_dictionary.py from the IAMC common-definitions in iam-data-chatbot/definitions/variable. Only variables published in IAMPARIS are kept.",
                "variables": dictionary,
            },
            indent=1,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )
    derived = sum(1 for entry in dictionary.values() if entry.get("derived"))
    missing = sorted(used - dictionary.keys())
    print(f"{len(definitions)} definitions expanded; {len(used)} IAMPARIS variables; {len(dictionary) - derived} defined, {derived} derived from a parent, {len(missing)} without any description")
    print("examples without any description:", missing[:12])


if __name__ == "__main__":
    main()
